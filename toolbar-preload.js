const { contextBridge, ipcRenderer } = require('electron');
require('./platform-ui');

contextBridge.exposeInMainWorld('nav', {
  go: (url) => ipcRenderer.send('omni:go', url),
  omniQuery: (text, rect) => ipcRenderer.send('omni:query', text, rect),
  omniKey: (key) => ipcRenderer.send('omni:key', key),
  omniHide: () => ipcRenderer.send('omni:hide'),
  back: () => ipcRenderer.send('nav', 'back'),
  forward: () => ipcRenderer.send('nav', 'forward'),
  reload: () => ipcRenderer.send('nav', 'reload'),
  home: () => ipcRenderer.send('nav', 'home'),
  setHome: () => ipcRenderer.send('nav', 'sethome'),
  menu: (x, y) => ipcRenderer.send('menu', x, y),
  muteTab: (id) => ipcRenderer.send('tab', 'mute', id),
  onMenuClosed: (cb) => ipcRenderer.on('menu-closed', () => cb()),
  toggleBookmark: () => ipcRenderer.send('bookmark:toggle'),
  barOpen: (url, newTab) => ipcRenderer.send('bar:open', url, !!newTab),
  barReorder: (id, beforeId) => ipcRenderer.send('bar:reorder', id, beforeId),
  barMenu: (id, x, y) => ipcRenderer.send('bar:menu', id, x, y),
  barAll: (x, y) => ipcRenderer.send('bar:all', x, y),
  barOverflow: (ids, x, y) => ipcRenderer.send('bar:overflow', ids, x, y),
  onBar: (cb) => ipcRenderer.on('bookmark:bar', (_e, s) => cb(s)),
  onBookmark: (cb) => ipcRenderer.on('bookmark:state', (_e, s) => cb(s)),
  pick: () => ipcRenderer.send('pick:toggle'),
  history: () => ipcRenderer.send('nav', 'history'),
  enableFlash: () => ipcRenderer.send('flash:enable'),
  update: () => ipcRenderer.send('nav', 'update'),
  onTasks: (cb) => ipcRenderer.on('tasks', (_e, s) => cb(s)),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, s) => cb(s)),
  onPickState: (cb) => ipcRenderer.on('pick:state', (_e, on) => cb(on)),
  siteInfo: (r) => ipcRenderer.send('siteinfo:open', r),
  account: (r) => ipcRenderer.send('account:open', r),
  onAccount: (cb) => ipcRenderer.on('account', (_e, s) => cb(s)),
  newTab: () => ipcRenderer.send('tab', 'new'),
  closeTab: (id) => ipcRenderer.send('tab', 'close', id),
  switchTab: (id) => ipcRenderer.send('tab', 'switch', id),
  moveTab: (id, beforeId) => ipcRenderer.send('tab', 'move', id, beforeId),
  tabMenu: (id) => ipcRenderer.send('tab', 'menu', id),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onTabs: (cb) => ipcRenderer.on('tabs', (_e, t) => cb(t)),
  onGhosthand: (cb) => ipcRenderer.on('ghosthand', (_e, s) => cb(s)),
  ghosthandDisconnect: () => ipcRenderer.send('ghosthand-disconnect'),
  ready: () => ipcRenderer.send('ready'),
});
